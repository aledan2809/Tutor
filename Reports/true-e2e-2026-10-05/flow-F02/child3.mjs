import {chromium,devices,BASE,mk} from './lib.mjs';
import fs from 'fs';
const VP=process.argv[2]||'mobile';
const opts= VP==='mobile'?{viewport:{width:375,height:812},deviceScaleFactor:2,isMobile:true,hasTouch:true,userAgent:devices['iPhone 13'].userAgent}:{viewport:{width:1440,height:900}};
const b=await chromium.launch(); const ctx=await b.newContext({...opts,storageState:`${VP}-child-state.json`}); const p=await ctx.newPage(); const m=mk(VP+'-c3',p);
const res=JSON.parse(fs.readFileSync(`${VP}-child-out.json`)); let taps=res.steps.find(s=>s.name==='after-subject').taps+1; const prevSec=parseFloat(res.steps.find(s=>s.name==='step1').sec); const t0=Date.now()-prevSec*1000;
const dump=async(name)=>{ await p.waitForTimeout(900); await m.snap(name);
  const txt=(await p.innerText('main').catch(()=>p.innerText('body'))).replace(/\n+/g,' | ').slice(0,900);
  res.steps.push({name,url:p.url().replace(BASE,''),sec:((Date.now()-t0)/1000).toFixed(1),taps,txt}); console.log('\n#',name,p.url().replace(BASE,''),((Date.now()-t0)/1000).toFixed(1)+'s taps',taps,'\n  ',txt); };
p.on('dialog',d=>{console.log('DIALOG',d.message());d.accept()});
await p.goto(BASE+'/ro/dashboard/practice?start=quick&domain=matematica-v-viii'); await p.waitForLoadState('networkidle'); await p.waitForTimeout(800);
const start=p.getByRole('button',{name:'Începe sesiunea'}).first();
const cov=await start.evaluate(e=>{const r=e.getBoundingClientRect();const el=document.elementFromPoint(r.left+r.width/2,Math.min(r.top+r.height/2,innerHeight-1));return {top:Math.round(r.top),bottom:Math.round(r.bottom),coveredBy:el&&!e.contains(el)?(el.closest('nav,a,button')?.innerText||el.tagName).slice(0,30):null}});
console.log('start btn',JSON.stringify(cov));

const sel=p.locator('select').first();
await sel.selectOption({label:'Clasa a VIII-a'}); taps++; await p.waitForTimeout(1200); await dump('class-chosen');
const cbs=await p.locator('main input[type=checkbox]').count(); console.log('checkboxes',cbs);
await b.close();
fs.writeFileSync(`${VP}-child-out.json`,JSON.stringify(res,null,1));
