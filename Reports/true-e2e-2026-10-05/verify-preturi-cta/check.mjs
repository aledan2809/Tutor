import { createRequire } from 'module';
import fs from 'fs';
const req = createRequire('/Users/danciulescu/Projects/Tester-Gateway/package.json');
const { chromium } = req('playwright');
const c = JSON.parse(fs.readFileSync(process.env.CREDS,'utf8'));
const BASE='http://localhost:3113';
const out='/Users/danciulescu/Projects/Tutor/Reports/true-e2e-2026-10-05/verify-preturi-cta/';
const b = await chromium.launch(); const p = await b.newPage();
await p.goto(BASE+'/ro/auth/signin');
await p.fill('form input[type=text]:first-of-type', c.email);
await p.fill('input[type=password]', c.password);
await p.click('button[type=submit]');
await p.waitForTimeout(2500);
console.log('after login url', p.url());
await p.goto(BASE+'/ro/preturi'); await p.waitForTimeout(800);
const hrefs = await p.$$eval('a', as=>as.filter(a=>/register|packages|dashboard/.test(a.href)).map(a=>a.textContent.trim().slice(0,30)+' -> '+a.getAttribute('href')));
console.log('preturi CTAs (logged in):', hrefs);
await p.screenshot({path: out+'01-preturi-logged-in.png', fullPage:true});
const r = await p.goto(BASE+'/ro/auth/register?plan=FAMILY'); await p.waitForTimeout(1200);
console.log('register status', r.status(), 'final url', p.url(), 'has email input', !!(await p.$('input[type=email]')));
await p.screenshot({path: out+'02-register-while-logged-in.png', fullPage:true});
await b.close();
